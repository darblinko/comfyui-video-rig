#!/usr/bin/env python3
"""Build one long clip per model from chained image-to-video segments.

Segment 1 starts from the spec's start_frame; every later segment starts from
the last frame of the previous segment's raw output. All segments share one
persona and camera description so the result reads as one continuous shot,
and every model gets the same seed for the same segment index so the
comparison stays like for like.

    python3 -u chain/run_chain.py jobs/headphones_test/chain.toml [--model wan22] [--start-seg 2]

Each segment is an ordinary run_job.py job: its TOML is written to
<spec dir>/generated/, and the extracted last frames and chain_state.json go to
outputs/<name>/. ffmpeg must be on PATH.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tomllib
from pathlib import Path

REPO_DIR = Path(__file__).resolve().parent.parent
SEGMENT_TIMEOUT_S = 3600


def load_spec(path: Path) -> dict:
    with open(path, "rb") as fh:
        spec = tomllib.load(fh)
    required = ("name", "models", "start_frame", "persona", "suffix", "negative_prompt", "beats", "seed_base")
    missing = [key for key in required if key not in spec]
    if missing:
        raise SystemExit(f"{path}: chain spec is missing {', '.join(missing)}")
    return {
        "job_type": "product_demo_video",
        "persona_id": "",
        "segment_seconds": 5,
        "resolution": [720, 1280],
        **spec,
        "spec_dir": path.resolve().parent,
    }


def stage_dir(spec: dict, repo_dir: Path = REPO_DIR) -> Path:
    return repo_dir / "outputs" / spec["name"]


def segment_start_image(spec: dict, model: str, seg: int) -> str:
    """Repo-relative start image for a segment."""
    if seg == 1:
        return spec["start_frame"]
    return f"outputs/{spec['name']}/{model}_seg{seg - 1}_last.png"


def segment_toml(spec: dict, model: str, seg: int) -> str:
    count = len(spec["beats"])
    prompt = f"{spec['persona']}, {spec['beats'][seg - 1]}, {spec['suffix']}"
    width, height = spec["resolution"]
    return (
        f"# Generated by run_chain.py: {model} segment {seg}/{count}\n"
        f'job_type = "{spec["job_type"]}"\n'
        f'persona_id = "{spec["persona_id"]}"\n'
        f'models = ["{model}"]\n\n'
        f'start_image = "{segment_start_image(spec, model, seg)}"\n\n'
        f'prompt = """{prompt}"""\n'
        f'negative_prompt = "{spec["negative_prompt"]}"\n\n'
        f"duration_seconds = {spec['segment_seconds']}\n"
        f"resolution = [{width}, {height}]\n"
        f"seed = {spec['seed_base'] + seg}\n"
    )


def run_job_command(job_toml: Path) -> list[str]:
    return [
        sys.executable,
        "runner/run_job.py",
        str(job_toml),
        "--no-sync",
        "--timeout",
        str(SEGMENT_TIMEOUT_S),
    ]


def last_frame_command(video: Path, out_png: Path) -> list[str]:
    """Seek to half a second before the end and keep overwriting one PNG, which
    leaves the final decoded frame."""
    return ["ffmpeg", "-y", "-loglevel", "error", "-sseof", "-0.5", "-i", str(video), "-update", "1", str(out_png)]


def run_folder_from_output(stdout: str) -> Path | None:
    prefix = "run folder: "
    folders = [line.removeprefix(prefix).strip() for line in stdout.splitlines() if line.startswith(prefix)]
    return Path(folders[-1]) if folders else None


def run_segment(spec: dict, model: str, seg: int, run=subprocess.run) -> Path:
    """Write the segment job, run it through run_job.py and return its raw clip."""
    generated = spec["spec_dir"] / "generated"
    generated.mkdir(parents=True, exist_ok=True)
    job_toml = generated / f"{model}_seg{seg}.toml"
    job_toml.write_text(segment_toml(spec, model, seg))
    print(f"=== chain: {model} segment {seg}/{len(spec['beats'])}", flush=True)

    proc = run(run_job_command(job_toml), cwd=REPO_DIR, capture_output=True, text=True)
    print(proc.stdout, flush=True)
    if proc.returncode != 0:
        print(proc.stderr, flush=True)
        raise RuntimeError(f"{model} segment {seg} failed (exit {proc.returncode})")
    run_folder = run_folder_from_output(proc.stdout)
    if run_folder is None:
        raise RuntimeError(f"{model} segment {seg}: run_job.py printed no run folder")
    raws = sorted((run_folder / model).glob("*.mp4"))
    if not raws:
        raise RuntimeError(f"{model} segment {seg}: no raw mp4 in {run_folder / model}")
    return raws[-1]


def extract_last_frame(video: Path, out_png: Path, run=subprocess.run) -> None:
    run(last_frame_command(video, out_png), check=True)
    if not out_png.exists():
        raise RuntimeError(f"last-frame extraction produced nothing: {out_png.name}")


def append_state(state_file: Path, record: dict) -> None:
    state = json.loads(state_file.read_text()) if state_file.exists() else []
    state_file.write_text(json.dumps([*state, record], indent=2) + "\n")


def repo_relative(path: Path, repo_dir: Path = REPO_DIR) -> str:
    return str(path.resolve().relative_to(repo_dir)) if path.resolve().is_relative_to(repo_dir) else str(path)


def run_model_chain(spec: dict, model: str, start_seg: int) -> None:
    stage = stage_dir(spec)
    for seg in range(start_seg, len(spec["beats"]) + 1):
        start_image = REPO_DIR / segment_start_image(spec, model, seg)
        if not start_image.exists():
            raise RuntimeError(f"missing start image {segment_start_image(spec, model, seg)}")
        raw = run_segment(spec, model, seg)
        last_png = stage / f"{model}_seg{seg}_last.png"
        extract_last_frame(raw, last_png)
        record = {"model": model, "segment": seg, "raw": repo_relative(raw), "last_frame": repo_relative(last_png)}
        append_state(stage / "chain_state.json", record)
        print(f"=== chain: {model} segment {seg} done: {record['raw']}", flush=True)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("spec", type=Path, help="chain spec TOML, e.g. jobs/headphones_test/chain.toml")
    parser.add_argument("--model", help="run only this model")
    parser.add_argument("--start-seg", type=int, default=1, help="resume the first model at this segment")
    args = parser.parse_args(argv)

    spec = load_spec(args.spec)
    if args.model and args.model not in spec["models"]:
        raise SystemExit(f"--model must be one of {spec['models']}")
    if not 1 <= args.start_seg <= len(spec["beats"]):
        raise SystemExit(f"--start-seg must be between 1 and {len(spec['beats'])}")
    stage_dir(spec).mkdir(parents=True, exist_ok=True)

    models = [args.model] if args.model else spec["models"]
    for model in models:
        run_model_chain(spec, model, args.start_seg if model == models[0] else 1)
    print("=== chain: all segments complete", flush=True)


if __name__ == "__main__":
    main()
