#!/usr/bin/env python3
"""Chained-segment driver for the headphones side-by-side test.

Each model gets a 20s clip built from four chained 5s segments: the next
segment's start image is the last frame of the previous segment's raw
output. Segment prompts share one persona/camera description so the clip
reads as a single continuous shot. Same seed per segment index across
models so the comparison stays apples-to-apples.

Run from the prototype dir (ffmpeg must be on PATH):
    python3 -u jobs/headphones_test/run_chain.py [--model wan22] [--start-seg 2]

Generated per-segment TOMLs land in jobs/headphones_test/generated/ and
staged frames + chain_state.json in outputs/headphones_test/.
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

PROTO = Path(__file__).resolve().parents[2]
STAGE = PROTO / "outputs" / "headphones_test"
GENERATED = PROTO / "jobs" / "headphones_test" / "generated"
STATE_FILE = STAGE / "chain_state.json"

MODELS = ["wan22", "hunyuan15"]
SEED_BASE = 555100
SEGMENT_TIMEOUT = 3600

PERSONA = (
    "photorealistic video of a cute geeky young woman in her early twenties, "
    "round glasses, dark messy bun, oversized lavender hoodie, fluffy pink "
    "cat-ear gaming headphones with glowing pink LED rings"
)
SUFFIX = (
    ", fixed static camera, no camera movement, cozy bedroom with soft RGB "
    "glow, warm lighting, realistic hand-object interaction"
)
NEGATIVE = (
    "camera pan, camera zoom, camera movement, dolly, scene cut, deformed "
    "hands, extra fingers, fused fingers, warped face, plastic skin, "
    "flickering, morphing, watermark, text, anime, cartoon"
)

SEGMENT_BEATS = [
    "wearing the headphones with both hands on the ear cups, she gently "
    "lifts the headphones off her head and lowers them to hold in front of "
    "her chest, speaking to the camera with natural mouth movement the "
    "whole time",
    "holding the fluffy pink cat-ear headphones in front of her chest, she "
    "rotates one ear cup toward the camera and points her index finger at "
    "the small USB-C charging port on the bottom edge of the ear cup, "
    "speaking to the camera with natural mouth movement",
    "she slowly moves the headphone ear cup closer to the camera until the "
    "ear cup with its glowing LED ring fills most of the frame, keeping her "
    "index finger next to the USB-C charging port, still speaking to the "
    "camera",
    "extreme close-up of the fluffy headphone ear cup held toward the "
    "camera, she taps her fingertip on the USB-C charging port and tilts "
    "the ear cup slightly so the port is clearly visible, still speaking",
]


def segment_toml(model: str, seg: int, start_image: Path) -> str:
    prompt = f"{PERSONA}, {SEGMENT_BEATS[seg - 1]}{SUFFIX}"
    rel_start = start_image.relative_to(PROTO)
    return (
        f"# Generated by run_chain.py: {model} segment {seg}/4\n"
        f'job_type = "product_demo_video"\n'
        f'persona_id = "presenter_desk_v1"\n'
        f'models = ["{model}"]\n\n'
        f'start_image = "{rel_start}"\n\n'
        f'prompt = """{prompt}"""\n'
        f'negative_prompt = "{NEGATIVE}"\n\n'
        f"duration_seconds = 5\n"
        f"resolution = [720, 1280]\n"
        f"seed = {SEED_BASE + seg}\n"
    )


def run_segment(model: str, seg: int, start_image: Path) -> Path:
    toml_path = GENERATED / f"{model}_seg{seg}.toml"
    toml_path.write_text(segment_toml(model, seg, start_image))
    print(f"=== chain: {model} seg {seg}/4 (start={start_image.name})", flush=True)

    cmd = [
        sys.executable, "runner/run_job.py", str(toml_path),
        "--no-sync", "--timeout", str(SEGMENT_TIMEOUT),
    ]
    proc = subprocess.run(cmd, cwd=PROTO, capture_output=True, text=True)
    print(proc.stdout, flush=True)
    if proc.returncode != 0:
        print(proc.stderr, flush=True)
        raise RuntimeError(f"{model} seg {seg} failed (exit {proc.returncode})")

    run_folder = None
    for line in proc.stdout.splitlines():
        if line.startswith("run folder: "):
            run_folder = Path(line.removeprefix("run folder: ").strip())
    if run_folder is None:
        raise RuntimeError(f"{model} seg {seg}: no run folder in output")

    raws = sorted((run_folder / model).glob("*.mp4"))
    if not raws:
        raise RuntimeError(f"{model} seg {seg}: no raw mp4 in {run_folder / model}")
    return raws[-1]


def extract_last_frame(video: Path, out_png: Path) -> None:
    subprocess.run(
        ["ffmpeg", "-y", "-loglevel", "error", "-sseof", "-0.5",
         "-i", str(video), "-update", "1", str(out_png)],
        check=True,
    )
    if not out_png.exists():
        raise RuntimeError(f"last-frame extraction produced nothing: {out_png}")


def append_state(record: dict) -> None:
    state = []
    if STATE_FILE.exists():
        state = json.loads(STATE_FILE.read_text())
    STATE_FILE.write_text(json.dumps(state + [record], indent=2))


def run_model_chain(model: str, start_seg: int) -> None:
    for seg in range(start_seg, 5):
        if seg == 1:
            start_image = STAGE / "frame0.png"
        else:
            start_image = STAGE / f"{model}_seg{seg - 1}_last.png"
        if not start_image.exists():
            raise RuntimeError(f"missing start image {start_image}")

        raw = run_segment(model, seg, start_image)
        last_png = STAGE / f"{model}_seg{seg}_last.png"
        extract_last_frame(raw, last_png)
        append_state({"model": model, "segment": seg, "raw": str(raw),
                      "last_frame": str(last_png)})
        print(f"=== chain: {model} seg {seg}/4 done -> {raw}", flush=True)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", choices=MODELS, help="run only this model")
    parser.add_argument("--start-seg", type=int, default=1, choices=[1, 2, 3, 4])
    args = parser.parse_args()

    GENERATED.mkdir(parents=True, exist_ok=True)
    STAGE.mkdir(parents=True, exist_ok=True)

    models = [args.model] if args.model else MODELS
    for model in models:
        start = args.start_seg if model == models[0] else 1
        run_model_chain(model, start)
    print("=== chain: all segments complete", flush=True)


if __name__ == "__main__":
    main()
